ALTER TABLE tbooker.show_seats DROP CONSTRAINT ck_show_seats_status;
ALTER TABLE tbooker.show_seats ADD CONSTRAINT ck_show_seats_status
    CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED'));

-- Keep permanent booking uniqueness. Holds have their own historical lifecycle.
ALTER TABLE tbooker.bookings ADD CONSTRAINT uq_bookings_id_owner_seat
    UNIQUE (id, user_id, show_seat_id);

CREATE TABLE tbooker.reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tbooker.users (id),
    show_seat_id BIGINT NOT NULL REFERENCES tbooker.show_seats (id),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    booking_id BIGINT UNIQUE,
    CONSTRAINT ck_reservations_status CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_reservations_times CHECK (expires_at > created_at),
    CONSTRAINT ck_reservations_booking CHECK ((status = 'CONFIRMED') = (booking_id IS NOT NULL)),
    CONSTRAINT fk_reservations_booking_owner_seat FOREIGN KEY (booking_id, user_id, show_seat_id)
        REFERENCES tbooker.bookings (id, user_id, show_seat_id)
);
-- No time-dependent index predicate: expiry transitions HELD rows in a transaction.
CREATE UNIQUE INDEX uq_reservations_held_seat ON tbooker.reservations (show_seat_id) WHERE status = 'HELD';
CREATE INDEX ix_reservations_expiry ON tbooker.reservations (expires_at, show_seat_id) WHERE status = 'HELD';
CREATE INDEX ix_reservations_user ON tbooker.reservations (user_id);
CREATE INDEX ix_reservations_seat ON tbooker.reservations (show_seat_id);
