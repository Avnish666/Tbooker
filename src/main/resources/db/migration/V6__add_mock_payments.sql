ALTER TABLE tbooker.reservations ADD CONSTRAINT uq_reservations_id_owner UNIQUE (id, user_id);

CREATE TABLE tbooker.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES tbooker.users (id),
    reservation_id BIGINT NOT NULL,
    method VARCHAR(20) NOT NULL CHECK (method IN ('UPI', 'CARD')),
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'INR'),
    idempotency_key VARCHAR(100) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9._:-]{1,100}$'),
    gateway_request_id UUID NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    provider_reference VARCHAR(100),
    provider_version BIGINT NOT NULL DEFAULT 0 CHECK (provider_version >= 0),
    confirmation_status VARCHAR(30) NOT NULL DEFAULT 'NOT_READY'
        CHECK (confirmation_status IN ('NOT_READY', 'PENDING', 'CONFIRMED', 'RECONCILIATION_REQUIRED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_payments_owner_key UNIQUE (user_id, idempotency_key),
    CONSTRAINT uq_payments_provider_reference UNIQUE (method, provider_reference),
    CONSTRAINT uq_payments_id_reservation_owner UNIQUE (id, reservation_id, user_id),
    CONSTRAINT fk_payments_reservation_owner FOREIGN KEY (reservation_id, user_id)
        REFERENCES tbooker.reservations (id, user_id),
    CONSTRAINT ck_payments_confirmation CHECK (
        (status = 'SUCCESS' AND confirmation_status IN ('PENDING', 'CONFIRMED', 'RECONCILIATION_REQUIRED'))
        OR (status <> 'SUCCESS' AND confirmation_status = 'NOT_READY')),
    CONSTRAINT ck_payments_verified CHECK (
        (provider_reference IS NULL AND provider_version = 0 AND status = 'PENDING')
        OR (provider_reference IS NOT NULL AND provider_version > 0))
);
-- One in-flight attempt per reservation. Multiple financial successes must remain
-- recordable if a provider later corrects a failure: the extra charge needs reconciliation.
CREATE UNIQUE INDEX uq_payments_pending_reservation ON tbooker.payments (reservation_id) WHERE status = 'PENDING';
CREATE INDEX ix_payments_reservation ON tbooker.payments (reservation_id, id);
CREATE INDEX ix_payments_owner_history ON tbooker.payments (user_id, created_at DESC, id DESC);
CREATE INDEX ix_payments_reconciliation ON tbooker.payments (confirmation_status, id) WHERE status = 'SUCCESS';

