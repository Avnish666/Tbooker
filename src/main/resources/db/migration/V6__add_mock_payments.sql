-- This table simulates a provider-owned ledger. Mock gateway operations commit it
-- in a separate transaction, never as part of an application booking transaction.
CREATE TABLE tbooker.mock_gateway_receipts (
    request_id UUID PRIMARY KEY,
    method VARCHAR(20) NOT NULL CHECK (method IN ('UPI', 'CARD')),
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency = 'INR'),
    provider_reference VARCHAR(100) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    version BIGINT NOT NULL CHECK (version > 0)
);
