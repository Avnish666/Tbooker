ALTER TABLE tbooker.reservations ADD CONSTRAINT fk_reservations_confirmed_payment
    FOREIGN KEY (confirmed_payment_id, id, user_id)
    REFERENCES tbooker.payments (id, reservation_id, user_id);
ALTER TABLE tbooker.reservations ADD CONSTRAINT ck_reservations_confirmed_payment
    CHECK (confirmed_payment_id IS NULL OR status = 'CONFIRMED');
